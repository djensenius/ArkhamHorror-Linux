//   scannerFlagsANewlyAddedFileAutomatically() and
//   discoverHeaderFilesUtilityDiscoversNestedHeadersToo()), never by the
//   real policy check, which instead uses the CMake-generated,
//   build-verified arkhamDomainHeaderInventory() exclusively.
//
//   noDomainHeaderDeclaresAJsonReturningEncoder() applies findViolations()
//   to every header named by arkhamDomainHeaderInventory() with no file
