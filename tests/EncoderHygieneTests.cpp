void EncoderHygieneTests::noDomainHeaderDeclaresAJsonReturningEncoder() {
  const QStringList headers = arkhamDomainHeaderInventory();
  QVERIFY2(headers.size() > 30,
           "expected the CMake-generated header inventory (see "
           "CMakeLists.txt's configure_file(tests/DomainHeaderInventory.h.in "
           "...)) to list the full src/ header set; generation may be "
           "broken");

  const QList<PinnedException> pins = pinnedExceptions();
  QList<int> matchCounts(pins.size(), 0);

  QList<Violation> unexpected;
  for (const QString &path : headers) {
    QVERIFY2(
        QFileInfo::exists(path),
        qPrintable(u"generated header inventory names a file that does "
                   "not exist on disk: %1 -- see CMakeLists.txt's "
                   "arkham_check_domain_header_inventory() gate"_s.arg(path)));
    for (const Violation &v : findViolationsInFile(path)) {
      QList<int> matched;
      if (isPinnedException(v, pins, &matched)) {
        for (int idx : matched)
          ++matchCounts[idx];
      } else {
        unexpected.append(v);
      }
    }
  }

  QVERIFY2(
      unexpected.isEmpty(),
      qPrintable(
          u"public Qt-JSON-returning (or macro-defining, or "
          "conversion-operator-to-a-banned-type) declaration(s) found in "
          "domain headers with no exact pinned justification -- domain "
          "values must expose only toRawJson()/toJsonBytes() and compose "
          "with the central Value::toExactQJson() family instead. If this "
          "is a genuinely new, reviewed, narrowly-scoped adapter, add an "
          "exact-text entry to pinnedExceptions() naming it explicitly; do "
          "not widen any existing rule/regex to accommodate it:\n%1"_s.arg(
              describeAll(unexpected))));

  QStringList stalePins;
  for (qsizetype i = 0; i < pins.size(); ++i) {
    if (matchCounts[i] == 0)
      stalePins.append(u"%1 [%2] %3 (%4)"_s.arg(pins[i].basename, pins[i].rule,
                                                pins[i].snippet,
                                                pins[i].justification));
  }
  QVERIFY2(
      stalePins.isEmpty(),
      qPrintable(
          u"pinnedExceptions() contains an entry that no longer matches any "
          "real declaration in the scanned headers (a stale/orphaned "
          "allowlist entry, most likely left over from a prior refactor) -- "
          "remove it:\n%1"_s.arg(stalePins.join(u'\n'))));
}

void EncoderHygieneTests::pinnedExceptionAppliesOnlyToExactTriple() {
  const QList<PinnedException> pins = {
      {u"Fake.h"_s, u"return-type"_s, u"QJsonObject toJson() const;"_s,
       u"test fixture"_s},
  };
  const Violation matching{u"Fake.h"_s, 1, u"return-type"_s,
                           u"QJsonObject toJson() const;"_s};
  const Violation differentText{u"Fake.h"_s, 1, u"return-type"_s,
                                u"QJsonObject toJsonDifferent() const;"_s};
  const Violation differentBasename{u"Other.h"_s, 1, u"return-type"_s,
                                    u"QJsonObject toJson() const;"_s};
  // Same exact text, but under a rule that must never be pinnable
  // regardless of its snippet -- a bare-auto/type-alias/
  // conversion-operator/macro-define violation can never be suppressed
  // by any pinned exception, no matter what text it happens to contain.
  const Violation differentRule{u"Fake.h"_s, 1, u"bare-auto"_s,
                                u"QJsonObject toJson() const;"_s};

  QVERIFY(isPinnedException(matching, pins));
  QVERIFY(!isPinnedException(differentText, pins));
  QVERIFY(!isPinnedException(differentBasename, pins));
  QVERIFY(!isPinnedException(differentRule, pins));
}

