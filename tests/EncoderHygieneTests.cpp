// Standing guard against the exact class of bug the cumulative reviews on
// issue #19/PR #20 kept re-finding across rounds: a public response/request
// encoder silently bypassing the resource-limit/duplicate-key/embedded-
// Undefined/lone-surrogate invariants Value::toExactQJson()/
// toExactQJsonObject()/toExactQJsonArray() (RawJson.h) enforce.
//
// Earlier versions of this test tried to police that by pattern-matching
// specific *shapes* a lossy encoder's body might take, and then tried
// exempting three whole header files (RawJson.h/JsonDecode.h/
// AuthModels.h) by basename from an otherwise-unconditional "no
// Qt-JSON-returning declaration" scan. Every round found either a new
// declaration shape the matcher didn't cover, or -- most recently -- a
// concrete way the whole-file exemption itself could be silently
// exploited: flip RawJson.h's private lossy conversion method to public,
// add a brand-new nested header under src/ that a non-recursive
// directory listing never visits, add a conversion-operator declaration
// (a shape the return-type regex never matched), or hide a banned return
// type behind a `#define`-based alias. All four passed the previous
// version of this test unchanged.
//
// This version closes each of those four specific gaps structurally
// rather than by growing another return-type-shape regex:
//
//   1. Value::toLossyQJsonForTestingOnly() no longer exists anywhere in
//      this production header/target at all -- public or private. It has
//      been relocated to tests/RawJsonLossyTestOnly.h (a header never
//      added to the arkham_foundation production target -- see
//      CMakeLists.txt) as a free function RawJson.h grants friendship to
//      by exact qualified name, not by a whole-class friend grant. There
//      is no access specifier left in RawJson.h to flip.
//   2. The header inventory scanned below (arkhamDomainHeaderInventory(),
//      generated by CMakeLists.txt's configure_file() from the exact
//      ARKHAM_FOUNDATION_HEADERS list add_library(arkham_foundation ...)
//      itself compiles) can never silently omit a new file: adding a
//      header anywhere under src/ -- including inside a brand-new nested
//      subdirectory -- without also registering it in
//      ARKHAM_FOUNDATION_HEADERS fails CMake *configuration* outright,
//      via cmake/DomainHeaderInventory.cmake's
//      arkham_check_domain_header_inventory() FATAL_ERROR gate, before
//      this test binary is even built. See
//      tests/cmake/DomainHeaderInventoryPolicyTest.cmake for the
//      dedicated ctest case proving that gate itself works.
//   3. findViolations() below now also flags a conversion-operator
//      declaration targeting a banned type (`operator QJsonObject()
//      const;` and friends) as its own rule, alongside the pre-existing
//      return-type/trailing-return-type/alias/bare-auto rules --
//      matching the reviewer's exact reported example, without
//      generalizing to "detect every possible conversion operator" (this
//      codebase's UrlValidator.h/ValueOrError.h both have a genuine,
//      unrelated `explicit operator bool() const noexcept;`, which must
//      keep compiling).
//   4. Every scanned domain header is now also checked for any
//      `#define` directive at all (see macroDefinePattern()) and flagged
//      unconditionally if one is present. No current header needs one
//      (confirmed: zero pre-existing `#define` usage anywhere under
//      src/), so this closes the entire "hide a banned type behind a
//      macro alias" evasion vector -- for every rule, not just
//      return-type -- without needing real preprocessing/macro
//      expansion at all: if a domain header cannot define a macro, it
//      cannot rename a banned type via one either.
//
// Finally, the whole-file exemption for RawJson.h/JsonDecode.h/
// AuthModels.h is gone. Every header in arkhamDomainHeaderInventory() is
// scanned unconditionally now; a small, explicit, per-basename allowlist
// of *exact* expected violation text (pinnedExceptions() below) is
// consulted instead, so a *different* or *new* declaration appearing in
// one of those three files -- even one that looks superficially similar
// -- is still flagged, and the allowlist itself is asserted to contain no
// stale/orphaned entry that no longer matches anything real.
//
//   findViolations() strips block/line comments and string/char literals
//   (so neither can smuggle a false match, in either direction) and then
//   flags, anywhere in the remaining text:
//     (a) a same-line or multi-line "TYPE name(" / "ValueOrError<TYPE> name("
//         / "std::optional<TYPE> name(" return-type-then-name-then-paren
//         adjacency, for TYPE in {QJsonObject, QJsonArray, QJsonValue};
//     (b) a trailing "-> TYPE" return type, optionally wrapped the same way;
//     (c) a `using X = ...TYPE...;` / `typedef ... TYPE ...;` alias that
//         would let a banned type hide behind a new name;
//     (d) any bare deduced-`auto` function declaration with no trailing
//         `-> Type` at all;
//     (e) a conversion-operator declaration targeting a banned type
//         (`operator (const)? TYPE (`);
//     (f) any `#define` directive at all, anywhere in the file.
//
//   discoverHeaderFiles() recursively lists every *.h file under a
//   directory via QDirIterator at test run time; it is used only by the
